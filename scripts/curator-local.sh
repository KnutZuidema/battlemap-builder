#!/usr/bin/env bash
# Run Curator as a native process on this machine while keeping every external
# dependency the cluster deployment uses.
#
#   * Secrets come from the cluster's `curator-secrets` Secret, so nothing is copied
#     by hand and nothing drifts from what the pod runs with.
#   * `DATABASE_URL` points at an in-cluster service (`*.svc.cluster.local`); the DSN
#     host is rewritten to 127.0.0.1 and a `kubectl port-forward` to that service is
#     held open for the lifetime of the process.
#   * R2/S3 blobs, OpenRouter, Modal, WaveSpeed, Hugging Face and Reddit are public
#     endpoints, so they need no forwarding.
#
# Usage:
#   scripts/curator-local.sh [--secrets-only] [-- <extra cargo args>]
#
# Environment:
#   CURATOR_NAMESPACE      namespace holding the secret        (default: curator)
#   CURATOR_SECRET_NAME    secret with the runtime credentials (default: curator-secrets)
#   CURATOR_LOCAL_ENV_FILE generated env file, mode 600        (default: curator/.env.cluster)
#   CURATOR_LOCAL_DB_PORT  local port for the Postgres forward (default: 5433)
#   PORT                   Curator HTTP port                   (default: 3002, read by Curator)
#
# Anything already exported in the shell wins over the generated file: Curator loads
# `CURATOR_ENV_FILE` with dotenvy, which never overrides process environment.

set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
namespace="${CURATOR_NAMESPACE:-curator}"
secret_name="${CURATOR_SECRET_NAME:-curator-secrets}"
env_file="${CURATOR_LOCAL_ENV_FILE:-$repo_root/curator/.env.cluster}"
db_port="${CURATOR_LOCAL_DB_PORT:-5433}"

secrets_only=0
while (($#)); do
  case "$1" in
    --secrets-only) secrets_only=1; shift ;;
    --) shift; break ;;
    *) break ;;
  esac
done

for tool in kubectl jq base64; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "curator-local: '$tool' is required but not on PATH" >&2
    exit 1
  }
done

secret_json="$(kubectl get secret "$secret_name" -n "$namespace" -o json)" || {
  echo "curator-local: cannot read Secret $namespace/$secret_name" >&2
  exit 1
}

# Secret keys are returned base64-encoded; decode each one into an associative array.
declare -A values=()
while IFS=$'\t' read -r key encoded; do
  [[ -n $key ]] || continue
  values["$key"]="$(printf '%s' "$encoded" | base64 -d)"
done < <(jq -r '.data // {} | to_entries[] | "\(.key)\t\(.value)"' <<<"$secret_json")

# Placeholder values from secret.yaml.template would send Curator at dead endpoints.
for key in "${!values[@]}"; do
  if [[ -z ${values[$key]} || ${values[$key]} == *your_* ]]; then
    unset 'values[$key]'
  fi
done

# Resolve the forwarded dependency (if any) before writing the file, so the DSN in
# the generated env file already points at the local forward.
db_url="${values[DATABASE_URL]:-}"
pf_svc=""
pf_ns=""
pf_remote_port=""
if [[ -n $db_url ]]; then
  authority="${db_url#*://}"
  authority="${authority%%/*}"
  host_port="${authority##*@}"
  host="${host_port%%:*}"
  if [[ $host_port == *:* ]]; then
    pf_remote_port="${host_port##*:}"
  else
    pf_remote_port=5432
  fi

  for suffix in .svc.cluster.local .svc; do
    [[ $host == *"$suffix" ]] || continue
    remainder="${host%"$suffix"}"
    pf_svc="${remainder%%.*}"
    pf_ns="${remainder#*.}"
    [[ $pf_ns != "$remainder" ]] || pf_ns="$namespace"
    break
  done

  if [[ -n $pf_svc ]]; then
    if [[ $host_port == *:* ]]; then
      values[DATABASE_URL]="${db_url/"$host:$pf_remote_port"/"127.0.0.1:$db_port"}"
    else
      values[DATABASE_URL]="${db_url/"$host"/"127.0.0.1:$db_port"}"
    fi
  fi
fi

tmp_env="$(mktemp)"
chmod 600 "$tmp_env"
{
  echo "# Generated by scripts/curator-local.sh from Secret $namespace/$secret_name."
  echo "# Never commit this file; it is excluded by .gitignore."
} >>"$tmp_env"

while IFS= read -r key; do
  value="${values[$key]}"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//$'\n'/\\n}"
  printf '%s="%s"\n' "$key" "$value" >>"$tmp_env"
done < <(printf '%s\n' "${!values[@]}" | sort)

mkdir -p -- "$(dirname -- "$env_file")"
install -m 600 "$tmp_env" "$env_file"
rm -f -- "$tmp_env"

echo "curator-local: wrote ${env_file#"$repo_root"/} (mode 600) from $namespace/$secret_name"
echo "curator-local: keys: $(printf '%s ' "${!values[@]}" | tr -s ' ')"
if [[ -n $pf_svc ]]; then
  echo "curator-local: DATABASE_URL -> 127.0.0.1:$db_port (forward to svc/$pf_svc -n $pf_ns:$pf_remote_port)"
elif [[ -n $db_url ]]; then
  echo "curator-local: DATABASE_URL already points outside the cluster; used as-is"
else
  echo "curator-local: DATABASE_URL empty; Curator runs on the filesystem catalog"
fi

if ((secrets_only)); then
  exit 0
fi

forward_pid=""
forward_log=""
cleanup() {
  if [[ -n $forward_pid ]]; then
    kill "$forward_pid" 2>/dev/null || true
    wait "$forward_pid" 2>/dev/null || true
  fi
  [[ -n $forward_log ]] && rm -f -- "$forward_log"
}
trap cleanup EXIT INT TERM

if [[ -n $pf_svc ]]; then
  forward_log="$(mktemp)"
  kubectl port-forward -n "$pf_ns" "svc/$pf_svc" "$db_port:$pf_remote_port" >"$forward_log" 2>&1 &
  forward_pid=$!

  ready=0
  for _ in $(seq 1 150); do
    if ! kill -0 "$forward_pid" 2>/dev/null; then
      echo "curator-local: port-forward to svc/$pf_svc failed:" >&2
      cat -- "$forward_log" >&2
      exit 1
    fi
    if (exec 3<>"/dev/tcp/127.0.0.1/$db_port") 2>/dev/null; then
      ready=1
      break
    fi
    sleep 0.1
  done
  if ((!ready)); then
    echo "curator-local: port 127.0.0.1:$db_port never opened (CURATOR_LOCAL_DB_PORT)" >&2
    cat -- "$forward_log" >&2
    exit 1
  fi
fi

export CURATOR_ENV_FILE="$env_file"
cd -- "$repo_root"
status=0
cargo run --manifest-path curator/Cargo.toml "$@" || status=$?
exit "$status"
